// FFT of HAETAE 1.2.0 (fft() of the reference fft.c) on the ARMv7E-M (Cortex-M4).
//
//   void fft(complex_fp32_16 data[256]);
//
// Same radix-2 butterflies as the reference, layer by layer:
//   t = root * data[odd],
//   (data[even], data[odd]) = (data[even] + t, data[even] - t),
// where the complex product uses the rounded fixed-point product
//   _mulrnd16(x, y) = (x * y + 2^15) >> 16.
// It is computed as SMMULR(y << 11, x << 5) = (x * y * 2^16 + 2^31) >> 32,
// which is the same value as long as |x| < 2^26 (so that x << 5 does not
// overflow); |y| <= 2^16 holds for all roots.  The inputs of KeyGen come from
// fft_init_and_bitrev() of polynomials with coefficients in [-2, 2], so
// |data| < 2^17 * (1 + 2^-16) before the first layer, each layer at most
// doubles the modulus (plus rounding), and the multiplied values stay below
// 2^25 (inputs of the eighth layer); the result is identical to the reference
// for coefficients up to 3 in absolute value.
//
// The twiddle table below is roots[2k] of the reference fft.c (Team HAETAE,
// MIT licence) shifted left by 11 bits, generated by a script from fft.c.

#include "params.h"

.syntax unified
.cpu cortex-m4
.thumb

.text
.align 2
.global HAETAE_NAMESPACE(fft)
.type HAETAE_NAMESPACE(fft), %function
HAETAE_NAMESPACE(fft):
    push    {r0, r4-r11, lr}        // [sp] = data
    mov     r0, #1024               // twiddle stride in bytes: 8 << (8 - r)
    mov     r1, #8                  // half the group size in bytes: 8 << (r - 1)
1:  // layer r
    ldr     r2, [sp]                // even pointer: first group
2:  // group
    adr     r12, fft_twiddles
    add     r3, r2, r1              // odd pointer
    mov     lr, r3                  // end of the group's even half
3:  // butterfly: (r6, r7) = data[even], (r8, r9) = data[odd], (r4, r5) = twiddle
    ldrd    r4, r5, [r12]
    ldrd    r6, r7, [r2]
    ldrd    r8, r9, [r3]
    add     r12, r12, r0
    lsl     r8, r8, #5
    lsl     r9, r9, #5
    smmulr  r10, r4, r8             // _mulrnd16(root.real, odd.real)
    smmulr  r11, r5, r9             // _mulrnd16(root.imag, odd.imag)
    sub     r10, r10, r11           // t.real
    smmulr  r11, r4, r9             // _mulrnd16(root.real, odd.imag)
    smmulr  r4, r5, r8              // _mulrnd16(root.imag, odd.real)
    add     r11, r11, r4            // t.imag
    add     r4, r6, r10
    add     r5, r7, r11
    sub     r6, r6, r10
    sub     r7, r7, r11
    strd    r6, r7, [r3], #8
    strd    r4, r5, [r2], #8
    cmp     r2, lr
    bne     3b
    mov     r2, r3                  // next group
    ldr     r4, [sp]
    add     r4, r4, #2048           // end of data
    cmp     r2, r4
    bne     2b
    lsr     r0, r0, #1
    lsl     r1, r1, #1
    cmp     r1, #2048
    bne     1b
    pop     {r0, r4-r11, pc}
.size HAETAE_NAMESPACE(fft), .-HAETAE_NAMESPACE(fft)

