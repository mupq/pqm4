// Constant-time CDT sampler for the HAETAE 1.2.0 half-Gaussian D_{Z,16}
// (SampleGauss83) on the ARMv7E-M (Cortex-M4).
//
//   uint32_t sample_gauss83_asm(uint32_t lo0, uint32_t lo1, uint32_t hi);
//
// returns  #{ i : CDT83[i] < rnd }  for the 83-bit input
//   rnd = hi * 2^64 + lo1 * 2^32 + lo0,   0 <= hi < 2^19,
// i.e. the same value as sample_gauss83() of the HAETAE 1.2.0 reference.
//
// Entries 0..75 (upper 19 bits below 0x7ffff, stored explicitly) are
// compared on 83 bits: CDT - rnd is computed with CMP/SBCS/SBCS and the
// carry (no borrow, i.e. CDT >= rnd) is accumulated with ADC.  Entries
// 76..165 all have the upper bits 0x7ffff; for them CDT < rnd holds iff
// hi == 0x7ffff and the lower 64 bits of CDT are below those of rnd, so only
// the lower 64 bits are compared and the count is multiplied by
// (hi == 0x7ffff) = (hi + 1) >> 19.
// The code is straight-line: the instruction sequence and the table
// addresses do not depend on the input.
//
// The table below is CDT83_LO/CDT83_HI of the HAETAE 1.2.0 reference
// (sampler.c, Team HAETAE, MIT licence), stored as little-endian words
// (lo[31:0], lo[63:32], hi) for entries 0..75 and (lo[31:0], lo[63:32])
// for entries 76..165.  It is generated by a script from sampler.c.

#include "config.h"

.syntax unified
.cpu cortex-m4
.thumb

// three entries with 83-bit comparison (9 words in r4-r12)
.macro cdt83_full3
    ldm     lr!, {r4-r12}
    cmp     r4, r0
    sbcs    r5, r5, r1
    sbcs    r6, r6, r2
    adc     r3, r3, #0
    cmp     r7, r0
    sbcs    r8, r8, r1
    sbcs    r9, r9, r2
    adc     r3, r3, #0
    cmp     r10, r0
    sbcs    r11, r11, r1
    sbcs    r12, r12, r2
    adc     r3, r3, #0
.endm

// one entry with 83-bit comparison (3 words in r4-r6)
.macro cdt83_full1
    ldm     lr!, {r4-r6}
    cmp     r4, r0
    sbcs    r5, r5, r1
    sbcs    r6, r6, r2
    adc     r3, r3, #0
.endm

// four entries with 64-bit comparison (8 words in r4-r11), count in r12
.macro cdt83_lo4
    ldm     lr!, {r4-r11}
    cmp     r4, r0
    sbcs    r5, r5, r1
    adc     r12, r12, #0
    cmp     r6, r0
    sbcs    r7, r7, r1
    adc     r12, r12, #0
    cmp     r8, r0
    sbcs    r9, r9, r1
    adc     r12, r12, #0
    cmp     r10, r0
    sbcs    r11, r11, r1
    adc     r12, r12, #0
.endm

// two entries with 64-bit comparison (4 words in r4-r7), count in r12
.macro cdt83_lo2
    ldm     lr!, {r4-r7}
    cmp     r4, r0
    sbcs    r5, r5, r1
    adc     r12, r12, #0
    cmp     r6, r0
    sbcs    r7, r7, r1
    adc     r12, r12, #0
.endm

.text
.align 2
.global HAETAE_NAMESPACE(sample_gauss83_asm)
.type HAETAE_NAMESPACE(sample_gauss83_asm), %function
HAETAE_NAMESPACE(sample_gauss83_asm):
    push    {r4-r11, lr}
    adr     lr, cdt83_table
    movs    r3, #0                  // #{i < 76  : CDT[i] >= rnd}

    // entries 0..74 (25 x 3) and 75
    .rept 25
    cdt83_full3
    .endr
    cdt83_full1

    mov     r12, #0                 // #{i >= 76 : CDT_lo[i] >= rnd_lo}

    // entries 76..163 (22 x 4) and 164..165
    .rept 22
    cdt83_lo4
    .endr
    cdt83_lo2

    // r = (76 - r3) + (90 - r12) * [hi == 0x7ffff]
    rsb     r12, r12, #90
    adds    r2, r2, #1
    lsrs    r2, r2, #19             // 1 iff hi == 0x7ffff (hi < 2^19)
    mul     r12, r12, r2
    rsb     r0, r3, #76
    add     r0, r0, r12
    pop     {r4-r11, pc}
.size HAETAE_NAMESPACE(sample_gauss83_asm), .-HAETAE_NAMESPACE(sample_gauss83_asm)

